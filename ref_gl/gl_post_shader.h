/* The scene has already been drawn. HUD and menus are drawn after this pass. */
static const char post_shader_source[] =
 "#version 110\n"
 "uniform sampler2D image, sceneDepth;\n"
 "uniform vec2 stepUV, endUV, effects, aoAndSharpen, depthRange, aoParams, colourStyle, sceneBrightness;\n"
 "vec2 inBounds(vec2 p){return clamp(p,stepUV*.5,endUV-stepUV*.5);}\n"
 "vec3 tap(vec2 p){return texture2D(image,inBounds(p)).rgb;}\n"
 "float lum(vec3 c){return dot(c,vec3(.299,.587,.114));}\n"
 /* Search along the dominant local edge and reject samples outside the contrast range. */
 "vec3 fxaa(vec2 p,vec3 c){\n"
 " float a=lum(tap(p+stepUV*vec2(-1.,1.))),b=lum(tap(p+stepUV));\n"
 " float d=lum(tap(p-stepUV)),e=lum(tap(p+stepUV*vec2(1.,-1.)));\n"
 " float m=lum(c),lo=min(m,min(min(a,b),min(d,e))),hi=max(m,max(max(a,b),max(d,e)));\n"
 " if(hi-lo<max(.035,hi*.125))return c;\n"
 " vec2 dir=vec2(d+e-a-b,a+d-b-e);\n"
 " float reduce=max((a+b+d+e)*.03125,.0078125);\n"
 " dir=clamp(dir/(min(abs(dir.x),abs(dir.y))+reduce),-8.,8.)*stepUV;\n"
 " vec3 inner=.5*(tap(p-dir/6.)+tap(p+dir/6.));\n"
 " vec3 outer=inner*.5+.25*(tap(p-dir*.5)+tap(p+dir*.5));\n"
 " float l=lum(outer);return (l<lo||l>hi)?inner:outer;\n"
 "}\n"
 /* Bright-pass blur of the SDR scene. */
 "vec3 bright(vec2 p){vec3 c=tap(p);return c*smoothstep(.58,.92,max(c.r,max(c.g,c.b)));}\n"
 "vec3 glow(vec2 p,vec2 t){\n"
 " return (bright(p+t*vec2(4.,0.))+bright(p-t*vec2(4.,0.))\n"
 " +bright(p+t*vec2(0.,4.))+bright(p-t*vec2(0.,4.)))*.12\n"
 " +(bright(p+t*vec2(9.,6.))+bright(p+t*vec2(-9.,6.))\n"
 " +bright(p+t*vec2(9.,-6.))+bright(p-t*vec2(9.,6.)))*.08;\n"
 "}\n"
 "float depthAt(vec2 p){\n"
 " float raw=texture2D(sceneDepth,inBounds(p)).r;\n"
 " return clamp((raw-depthRange.x)*depthRange.y,0.,1.);\n"
 "}\n"
 "float eyeDepth(float d){return 4.*aoParams.x/(aoParams.x-d*(aoParams.x-4.));}\n"
 /* BDGN 3.57h: the view weapon is drawn in the nearest 30 % of the depth range (RF_DEPTHHACK); its depth is not a real
   distance, so it gets no ambient occlusion and casts none (it shaded the weapon in bands that moved with it) */
"float occluder(vec2 p,float z){float e=depthAt(p);if(e<.3)return 0.;float delta=z-eyeDepth(e);\n"
 " return smoothstep(1.5,6.,delta)*(1.-smoothstep(14.,48.,delta));}\n"
 "float occlusion(vec2 p){\n"
 " float d=depthAt(p);if(d>=.99999||d<.3)return 0.;\n"
 " float z=eyeDepth(d);vec2 t=stepUV*clamp(aoParams.y/z,2.,16.);\n"
  /* BDGN 3.56: nothing beyond 2000 units. The sky box (2300 and more away) is a hollow cube, and its edges are the
    deepest points of their surroundings: ambient occlusion drew them as dark lines across the sky. */
 " if(z>2000.)return 0.;\n"
 " float keep=1.-smoothstep(1400.,2000.,z);\n"
 " return keep*.125*(occluder(p+vec2(t.x,0.),z)+occluder(p-vec2(t.x,0.),z)\n"
 " +occluder(p+vec2(0.,t.y),z)+occluder(p-vec2(0.,t.y),z)\n"
 " +occluder(p+t*vec2(.6,.6),z)+occluder(p-t*vec2(.6,.6),z)\n"
 " +occluder(p+t*vec2(.6,-.6),z)+occluder(p+t*vec2(-.6,.6),z));\n"
 "}\n"
 /* Spatial reconstruction follows the edge tangent and limits sharpening to the local colour range. */
 "vec3 adaptive(vec2 p,vec3 c){\n"
 " vec2 x=vec2(stepUV.x,0.),y=vec2(0.,stepUV.y);\n"
 " vec3 l=tap(p-x),r=tap(p+x),u=tap(p+y),d=tap(p-y);\n"
 " vec2 gradient=vec2(lum(r)-lum(l),lum(u)-lum(d));\n"
 " float edge=length(gradient);vec2 tangent=vec2(-gradient.y,gradient.x)/max(edge,.001);\n"
 " vec2 offset=tangent*stepUV*.65;\n"
 " vec3 base=mix(c,(tap(p-offset)+tap(p+offset))*.5,smoothstep(.035,.25,edge)*.45);\n"
 " vec3 soft=(l+r+u+d)*.25;\n"
 " vec3 lo=min(c,min(min(l,r),min(u,d))),hi=max(c,max(max(l,r),max(u,d)));\n"
 " float amount=mix(.42,.18,smoothstep(.08,.55,lum(hi-lo)));\n"
 " return clamp(base+amount*(base-soft),lo,hi);\n"
 "}\n"
 "void main(){\n"
 " vec2 p=gl_TexCoord[0].st;vec3 c=tap(p);\n"
 " if(effects.x>0.)c=fxaa(p,c);\n"
 " if(aoAndSharpen.y>1.5)c=adaptive(p,c);\n"
 " else if(aoAndSharpen.y>0.){\n"
 "  vec3 l=tap(p-vec2(stepUV.x,0.)),r=tap(p+vec2(stepUV.x,0.));\n"
 "  vec3 u=tap(p+vec2(0.,stepUV.y)),d=tap(p-vec2(0.,stepUV.y));\n"
 "  float axis=clamp(.5+(abs(lum(l)-lum(r))-abs(lum(u)-lum(d)))*2.,0.,1.);\n"
 "  vec3 s=mix((l+r)*.5,(u+d)*.5,axis);\n"
 "  c=clamp(c+.28*(c-s),min(c,min(min(l,r),min(u,d))),max(c,max(max(l,r),max(u,d))));\n"
 " }\n"
 " if(aoAndSharpen.x>0.)c*=1.-aoAndSharpen.x*occlusion(p);\n"
 " if(effects.y>0.)c+=glow(p,stepUV)*effects.y;\n"
 " if(colourStyle.x>0.){\n"
 "  c=max(c,0.);\n"
 "  c=(c*(2.51*c+.03))/(c*(2.43*c+.59)+.14);\n"
 " }\n"
 " if(colourStyle.y>0.){\n"
 "  vec3 tint=colourStyle.y<1.5?vec3(1.07,1.,.91):vec3(.92,1.,1.07);\n"
 "  c=mix(vec3(lum(c)),c,.91)*tint;\n"
 " }\n"
 " if(sceneBrightness.x!=1.) c=pow(clamp(c,0.,1.),vec3(sceneBrightness.x));\n"
 " gl_FragColor=vec4(clamp(c,0.,1.),1.);\n"
 "}\n";
