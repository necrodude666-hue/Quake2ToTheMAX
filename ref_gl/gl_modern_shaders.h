 "varying vec3 worldPos; varying vec4 colour;\n"
 "void main(){gl_Position=ftransform();worldPos=gl_Vertex.xyz;colour=gl_Color;gl_TexCoord[0]=gl_MultiTexCoord0;}";

static const char modern_puff_shader[] =
 "#version 110\n"
 "uniform sampler2D puffTex,opaqueDepth;uniform vec4 viewport;uniform vec2 textureSize,range;\n"
 "uniform vec4 lightPos[4],lightCol[4];uniform vec2 options;uniform float softEnabled;\n"
 "varying vec3 worldPos;varying vec4 colour;\n"
 "float linearZ(float z){float d=clamp((z-range.x)*range.y,0.,1.);return 4.*options.y/(options.y-d*(options.y-4.));}\n"
 "void main(){vec4 c=texture2D(puffTex,gl_TexCoord[0].xy)*colour;float fade=1.;\n"
 "if(softEnabled>0.){vec2 uv=(gl_FragCoord.xy-viewport.xy)/textureSize;float z=texture2D(opaqueDepth,uv).r;"
 "fade=clamp((linearZ(z)-linearZ(gl_FragCoord.z))/12.,0.,1.);}\n"
 "vec3 light=vec3(0.);for(int i=0;i<4;i++){float a=clamp(1.-length(lightPos[i].xyz-worldPos)*lightPos[i].w,0.,1.);light+=lightCol[i].rgb*a*a;}\n"
 "c.rgb*=vec3(1.)+clamp(light,0.,.8);c.a*=fade;if(options.x>0.)c.rgb*=fade;gl_FragColor=c;}";

static const char modern_screen_shader[] =
 "#version 110\n"
 "uniform sampler2D scene,depthTex,materialTex;uniform vec4 viewport;uniform vec2 textureSize,range;\n"
 "uniform mat4 inverseProjection,projection;uniform vec4 modes;uniform vec4 params;\n"
 "uniform sampler2D waterMask;uniform vec4 waterData,waterDirection,waterColour,waterSource;uniform vec2 waterModes;\n"
 "uniform vec4 eyeOrigin,rightAxis,upAxis,forwardAxis;uniform vec4 lightPos[4],lightCol[4];\n"
 "vec2 bound(vec2 uv){return clamp(uv,vec2(.5)/textureSize,(viewport.zw-vec2(.5))/textureSize);}\n"
 "vec2 texUV(vec2 uv){return bound(uv*viewport.zw/textureSize);}\n"
 "float depth(vec2 uv){float d=texture2D(depthTex,texUV(uv)).r;return clamp((d-range.x)*range.y,0.,1.);}\n"
 "vec3 position(vec2 uv){vec4 p=inverseProjection*vec4(uv*2.-1.,depth(uv)*2.-1.,1.);return p.xyz/max(abs(p.w),.00001);}\n"
 "vec3 world(vec3 p){return eyeOrigin.xyz+rightAxis.xyz*p.x+upAxis.xyz*p.y-forwardAxis.xyz*p.z;}\n"
 "vec3 color(vec2 uv){return texture2D(scene,texUV(uv)).rgb;}\n"
 /* The mask may move with the camera; the wave phase must never move with it.
    Point lights use the sample's position, not a cached direction at the eye. */
 "vec3 waterRay(vec3 w){vec3 d=waterDirection.xyz;if(waterSource.w>0.){vec3 a=normalize(waterSource.xyz-w);vec2 r=a.xy*.7501875;d=vec3(r,sqrt(max(.01,1.-dot(r,r))));}return d;}\n"
 "vec2 waterEntry(vec3 w){vec3 d=waterRay(w);return w.xy+d.xy*(waterData.x-w.z)/max(d.z,.1);}\n"
 "vec2 waterUV(vec3 w){return (waterEntry(w)-waterData.yz)*waterData.w;}\n"
 "float entry(vec2 s){float edge=smoothstep(0.,.045,min(min(s.x,1.-s.x),min(s.y,1.-s.y)));return texture2D(waterMask,clamp(s,.001,.999)).r*edge;}\n"
 "float caustic(vec2 xy,float t){\n"
 " vec2 q=xy*.035;\n"
 " q+=vec2(sin(q.y*1.17+t*.63)+sin(q.x*.83-t*.41),cos(q.x*1.31-t*.58)+sin(q.y*.71+t*.37))*.55;\n"
 " float a=sin(q.x+sin(q.y*1.43+t*.72)*1.4+t*.49);\n"
 " float b=cos(q.y*1.19+sin(q.x*1.37-t*.57)*1.3-t*.66);\n"
 " float ridge=abs(a+b);float blur=max(.15,fwidth(ridge)*1.8);\n"
 " return 1.-smoothstep(.06,.32+blur,ridge);\n"
 "}\n"
 "void main(){vec2 uv=(gl_FragCoord.xy-viewport.xy)/viewport.zw;vec3 c=color(uv);float d=depth(uv);\n"
 "if(d>=.99999){gl_FragColor=vec4(c,1.);return;}vec3 p=position(uv);vec3 w=world(p);\n"
 "vec3 n=normalize(cross(dFdx(p),dFdy(p)));if(dot(n,-p)<0.)n=-n;\n"
 "if(modes.x>0.){vec4 mat=texture2D(materialTex,texUV(uv));float weight=(1.-mat.r)*(.04+.55*mat.g)*mat.a;\n"
 "if(weight>.015){vec3 ray=reflect(normalize(p),n);vec3 hit=vec3(0.);float found=0.;\n"
 "for(int i=0;i<32;i++){if(float(i)>=modes.x*16.)break;vec3 q=p+n*2.+ray*(6.+float(i)*12.);\n"
 "vec4 clip=projection*vec4(q,1.);if(clip.w<=0.)break;vec2 s=clip.xy/clip.w*.5+.5;\n"
 "if(s.x<0.||s.x>1.||s.y<0.||s.y>1.)break;vec3 at=position(s);float delta=at.z-q.z;\n"
 "if(depth(s)<.99999&&delta>0.&&delta<12.){float edge=smoothstep(0.,.12,min(min(s.x,1.-s.x),min(s.y,1.-s.y)));hit=color(s);found=edge;break;}}\n"
 "float fres=.12+.88*pow(1.-max(dot(normalize(-p),n),0.),5.);c=mix(c,hit,found*weight*fres);}}\n"
 "if(modes.y>0.){vec3 bounce=vec3(0.);float total=0.;\n"
 "for(int i=0;i<16;i++){if(float(i)>=modes.y*8.)break;float a=float(i)*2.399963;float radius=4.+float(i)*1.5;\n"
 "vec2 s=uv+vec2(cos(a),sin(a))*radius/viewport.zw;\n"
 "if(s.x>0.&&s.x<1.&&s.y>0.&&s.y<1.&&depth(s)<.99999){vec3 delta=position(s)-p;float dist=length(delta);\n"
 "float amount=max(dot(n,delta/max(dist,.01)),0.)*(1.-smoothstep(8.,96.,dist));bounce+=color(s)*amount;total+=1.;}}\n"
 "c+=bounce/max(total,1.)*.18*(1.-clamp(dot(c,vec3(.299,.587,.114)),0.,1.));}\n"
 "if(modes.z>0.){vec3 fog=vec3(.09,.12,.15);float len=min(length(p),1800.);vec3 scatter=vec3(0.);\n"
 "for(int i=0;i<16;i++){if(float(i)>=modes.z*8.)break;float f=(float(i)+.5)/(modes.z*8.);vec3 samplePos=world(p*f);\n"
 "float density=.65+.35*sin(samplePos.x*.006+samplePos.y*.004+samplePos.z*.008);vec3 lit=vec3(.10,.13,.16);\n"
 "for(int j=0;j<4;j++){float a=clamp(1.-length(lightPos[j].xyz-samplePos)*lightPos[j].w,0.,1.);lit+=lightCol[j].rgb*a*a;}scatter+=lit*density;}\n"
 "float opacity=min(.22,1.-exp(-len*.00022));fog=mix(fog,scatter/(modes.z*8.),.65);c=mix(c,fog,opacity);}\n"
 "if(waterDirection.w>0. && w.z<waterData.x){\n"
 " vec3 wn=normalize(rightAxis.xyz*n.x+upAxis.xyz*n.y-forwardAxis.xyz*n.z);\n"
 " vec2 s=waterUV(w);float mask=entry(s);float deep=waterData.x-w.z;\n"
 " if(waterModes.x>0.){\n"
 "  float focus=caustic(waterEntry(w),params.x);\n"
 "  float incidence=max(dot(wn,waterRay(w)),0.);\n"
 "  float energy=mask*texture2D(materialTex,texUV(uv)).b*exp(-deep*.0035)*incidence;\n"
 "  c+=waterColour.rgb*vec3(.055,.095,.11)*focus*energy;\n"
 " }\n"
 " if(waterModes.y>0.){\n"
 "  float len=min(length(p),1600.);vec3 shaft=vec3(0.);float samples=waterModes.y>1.?24.:12.;\n"
 "  for(int i=0;i<24;i++){\n"
 "   if(float(i)>=samples)break;float f=(float(i)+.5)/samples;vec3 at=world(p*f);\n"
 "   if(at.z<waterData.x){\n"
 "    vec2 es=waterUV(at);float open=entry(es);float dep=waterData.x-at.z;\n"
 "    vec2 drift=vec2(sin(at.z*.009+params.x*.36),cos(at.z*.012-params.x*.31))*7.;\n"
 "    float beam=caustic(waterEntry(at)+drift,params.x*.7);\n"
 "    shaft+=waterColour.rgb*(.12+.88*beam)*open*exp(-dep*.004);\n"
 "   }\n"
 "  }\n"
 "  vec3 transmission=exp(-len*vec3(.0016,.00075,.0004));\n"
 "  c=c*transmission+vec3(.015,.065,.085)*(1.-transmission);\n"
 "  c+=shaft/samples*min(.22,len*.0004);\n"
 " }\n"
 "}\n"
 "gl_FragColor=vec4(clamp(c,0.,1.),1.);}";
